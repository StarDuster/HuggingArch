"""Headless tests for the Playground model editor (layer groups).

Same harness as `test_pages_smoke.py`: the built `web/dist`, every backend
path stubbed, headless chromium. The stubs are real backend answers
(`fixtures/playground_editor.json`, regenerated by running this file as a
script), so the page is exercised on the DTO the API actually returns. The
page computes nothing: what it sends is asserted from the request body,
what it shows from the rendered rows.
"""

from __future__ import annotations

import json

from tests.frontend.test_pages_smoke import Session, _FIXTURES, browser_base  # noqa: F401  (fixture)
from tests.frontend.test_playground_frontend import _COMPONENTS

_SKELETON = "/api/playground/model-skeleton"
_COMPOSE = "/api/playground/compose-model"
_BENCH = "/api/playground/module-bench"


def _raw_fixture() -> dict:
    return json.loads((_FIXTURES / "playground_editor.json").read_text())


def _fixture() -> dict:
    """Skeleton + compose stubs. Success compose entries carry the 5a
    target keys (`phases`, `kv_storage_by_cache_len`) before they reach
    the page; the on-disk fixture may still be a pre-5a dump."""
    data = _raw_fixture()
    data["compose"] = {k: _with_phases(v) for k, v in data["compose"].items()}
    return data


def _idle_compose() -> dict:
    """Load-only auto-compose: edited equals base, no group rows."""
    units = {"flops": "", "act_bytes": "", "traffic": "", "weight_read": "", "kv_bytes": ""}
    phase = {
        "flops": 0, "act_bytes_naive": 0, "act_bytes_fused": 0,
        "weight_read_bytes": 0, "kv_step_bytes": 0, "kv_read_bytes": 0,
        "memory_dominant": "weights", "units": units,
    }
    whole = {
        "params": 0, "active_params": 0, "flops": 0, "weight_bytes": 0,
        "kv_bytes_at_L": 0, "act_bytes_naive": 0, "act_bytes_fused": 0,
        "phases": {"prefill": dict(phase), "decode": dict(phase)},
        "kv_storage_by_cache_len": [],
    }
    return {"success": True, "composed": whole, "base": whole, "rows": []}


def _with_phases(compose: dict) -> dict:
    """Attach the 5a fields the editor summary / KV / step charts read.
    Prefill copies the existing whole-model totals; decode is a distinct
    copy so tests can see the page is not rereading prefill."""
    if not compose.get("success"):
        return compose
    out = json.loads(json.dumps(compose))
    units = {"flops": "whole model", "act_bytes": "whole model",
             "traffic": "whole model", "weight_read": "whole model", "kv_bytes": "whole model"}
    for side in ("composed", "base"):
        w = out[side]
        if "phases" not in w:
            w["phases"] = {
                "prefill": {
                    "flops": w["flops"],
                    "act_bytes_naive": w["act_bytes_naive"],
                    "act_bytes_fused": w["act_bytes_fused"],
                    "weight_read_bytes": w["weight_bytes"],
                    "kv_step_bytes": w["kv_bytes_at_L"],
                    "units": units,
                },
                "decode": {
                    "flops": w["flops"] // 4096,
                    "act_bytes_naive": w["act_bytes_naive"] // 4096,
                    "act_bytes_fused": w["act_bytes_fused"] // 4096,
                    "weight_read_bytes": w["weight_bytes"],
                    "kv_read_bytes": w["kv_bytes_at_L"],
                    "memory_dominant": "kv",
                    "units": units,
                },
            }
        if "kv_storage_by_cache_len" not in w:
            L = 2048
            w["kv_storage_by_cache_len"] = [
                {"cache_len": n, "storage_bytes": w["kv_bytes_at_L"] if n == L else w["kv_bytes_at_L"] * n // L}
                for n in (1024, 2048, 4096)
            ]
    return out


def _editor(browser_base, model_id: str, compose: dict | None = None,  # noqa: F811
            width: int = 1440, before=None) -> Session:
    browser, base = browser_base
    data = _fixture()
    stubs = {"/api/playground/components": _COMPONENTS,
             _SKELETON: data["skeleton"][model_id],
             _COMPOSE: compose if compose is not None else _idle_compose()}
    s = Session(browser, base, stubs)
    s.page.set_viewport_size({"width": width, "height": 900})
    s.goto("/playground.html")
    s.page.evaluate("localStorage.clear()")
    if before:
        before(s.page)
    s.goto("/playground.html")
    s.page.click("text=Model editor")
    s.page.fill("input[list=pg-models]", model_id)
    s.page.click("#pg-load")
    s.page.wait_for_selector("#pg-group-table", timeout=15000)
    assert s.wait_for(lambda: s.count(_COMPOSE) > 0, timeout_ms=15000)
    s.page.wait_for_selector(
        "#pg-group-table[data-compose-state=done], .pg-editor-error", timeout=15000)
    return s


def _composed(s: Session, n: int) -> dict:
    """After an edit: wait for a new compose-model request, then for the
    table to render that response (seq matches the request count)."""
    assert s.wait_for(lambda: s.count(_COMPOSE) > n, timeout_ms=15000)
    s.page.wait_for_selector(
        "#pg-group-table[data-compose-state=done], .pg-editor-error", timeout=15000)

    def caught_up():
        el = s.page.query_selector("#pg-group-table")
        if el is None:
            return False
        seq = el.get_attribute("data-compose-seq")
        state = el.get_attribute("data-compose-state")
        return state in ("done", "error") and seq == str(s.count(_COMPOSE))

    assert s.wait_for(caught_up, timeout_ms=15000)
    return s.requests[_COMPOSE][-1]["body"]


