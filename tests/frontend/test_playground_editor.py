def test_a_dim_value_that_is_not_a_count_is_not_sent(browser_base):  # noqa: F811
    """A dim counts something: a negative or fractional value is marked on
    its input and no compose is sent for it."""
    s = _editor(browser_base, "moonshotai/Kimi-K3")
    s.page.click("tr[data-group='3'] .pg-dims-toggle")
    box = s.page.locator("tr[data-group-dims='3'] .pg-group-dims input[type=number]").first
    n = s.count(_COMPOSE)
    for raw, said in (("-8", "cannot be negative"), ("2.5", "must be a whole number")):
        box.fill(raw)
        s.page.wait_for_timeout(900)
        assert said in s.page.locator(".pg-dim-invalid").first.inner_text()
        assert s.count(_COMPOSE) == n
    s.assert_clean()


