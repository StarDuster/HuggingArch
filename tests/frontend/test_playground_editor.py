def test_a_swap_opens_old_vs_new_graph_diff(browser_base):  # noqa: F811
    data = _fixture()
    s = _editor(browser_base, "moonshotai/Kimi-K3", data["compose"]["kimi_group3"])
    s.stubs[_BENCH] = {
        "success": True,
        "base_model_id": "moonshotai/Kimi-K3",
        "contract": {"batch": 1, "input_tokens": 2048, "dim_overrides": {},
                     "phases": {"prefill": {"batch": 1, "s_query": 2048, "s_kv": 2048},
                                "decode": {"batch": 1, "s_query": 1, "s_kv": 2048}}},
        "results": [], "errors": [],
        "graph_diff": {"available": False, "reason": "incompatible roles"},
    }
    n = s.count(_COMPOSE)
    s.page.select_option("tr[data-group='3'] select[data-slot='self_attn']",
                         "mla_output_gate_attention")
    _composed(s, n)
    assert s.count(_BENCH) == 0
    s.page.click("text=old vs new")
    # Group 3's declaration runs as several calls of the base: nothing is
    # benched until the user names the one to evaluate the swap at.
    (slot,) = [sl for g in _fixture()["skeleton"]["moonshotai/Kimi-K3"]["groups"]
               if g["group_id"] == 3 for sl in g["slots"] if sl["slot_id"] == "self_attn"]
    assert len(slot["calls"]) > 1
    pick = s.page.locator("[data-slot-diff] select[data-call-pick]")
    pick.wait_for(state="visible", timeout=15000)
    s.page.wait_for_timeout(300)
    assert s.count(_BENCH) == 0
    call = slot["calls"][1]["call"]
    pick.select_option(call)
    assert s.wait_for(lambda: s.count(_BENCH) > 0, timeout_ms=15000)
    body = s.requests[_BENCH][-1]["body"]
    assert body["base_model_id"] == "moonshotai/Kimi-K3"
    assert body["entries"][0]["name"] == "kimi_k3_kda_attention"
    assert body["entries"][0]["model_id"] == "moonshotai/Kimi-K3"
    assert body["entries"][1]["name"] == "mla_output_gate_attention"
    assert body["entries"][1]["dims"] == {}
    assert [e["call"] for e in body["entries"]] == [call, call]
    s.page.wait_for_selector("[data-diff-refused]", timeout=15000)
    assert "incompatible roles" in s.page.inner_text("[data-diff-refused]")
    s.assert_clean()


