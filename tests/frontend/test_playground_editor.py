def test_serving_contract_lives_on_the_sections_that_consume_it(browser_base):  # noqa: F811
    """Editor top card is model + Load; B / L / GPU sit on summary and KV,
    share one state, and still ride compose-model; the page's precision
    preset rides it too."""
    data = _fixture()
    s = _editor(browser_base, "moonshotai/Kimi-K3",
                _with_phases(data["compose"]["kimi_group3"]))
