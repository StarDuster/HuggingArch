def test_group_rows_add_up_to_the_whole_model(browser_base):  # noqa: F811
    """Every per-group column is the group's total over its layers: the
    group rows (the vision tower's included) plus the model level are the
    whole-model summary."""
    data = _fixture()
    payload = _with_phases(data["compose"]["kimi_group3"])
    composed = payload["composed"]
    s = _editor(browser_base, "moonshotai/Kimi-K3", payload)
    n = s.count(_COMPOSE)
    s.page.select_option("tr[data-group='3'] select[data-slot='self_attn']",
                         "mla_output_gate_attention")
    _composed(s, n)

    def column(col):
        return sum(int(v) for v in s.page.eval_on_selector_all(
            f"#pg-group-table td[data-col='{col}']", "cells => cells.map(c => c.dataset.edited)"))

    def summary(col):
        return int(s.page.locator(
            f'#pg-summary table tbody tr[data-entry="edited"] td[data-col="{col}"]'
        ).get_attribute("data-value"))

    assert column("params") == summary("params") == composed["params"]
    assert column("flops") == summary("prefill_flops") == composed["phases"]["prefill"]["flops"]
    assert column("kv") == summary("kv_storage") == composed["kv_bytes_at_L"]
    assert column("weight_bytes") == summary("weight_bytes") == composed["weight_bytes"]
    assert all("group total" in h for h in s.page.eval_on_selector_all(
        "#pg-group-table thead th.pg-g-num", "hs => hs.map(h => h.textContent)"))
    s.assert_clean()


