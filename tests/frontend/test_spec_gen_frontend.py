"""Inspector spec-job polling and refine-is-opt-in contracts."""
from __future__ import annotations

import os
import shutil
import subprocess
from pathlib import Path

import pytest

PROJECT_ROOT = Path(__file__).resolve().parents[2]
WEB = PROJECT_ROOT / "web"


def _missing(reason: str) -> None:
    if os.environ.get("CI"):
        pytest.fail(f"spec-gen frontend test cannot run in CI: {reason}")
    pytest.skip(reason)


def test_analyze_success_does_not_post_refine():
    """Analyze with a non-zero storage_diff must not start refine. The Refine
    button's onClick is the only call site."""
    src = (WEB / "src" / "pages" / "Inspector.tsx").read_text()
    run_start = src.index("const run = useCallback")
    run_end = src.index("runRef.current = run")
    run_body = src[run_start:run_end]
    assert "refineSpec(" not in run_body
    assert "shouldAutoFix(body)" in run_body
    assert "void fixSpec(" in run_body
    assert "urls.refine" not in run_body
    assert "/api/spec/refine" not in run_body
    assert "/refine-spec" not in run_body
    btn_start = src.index('id="custom-refine-btn"')
    btn_end = src.index("</button>", btn_start)
    assert src[btn_start:btn_end].count("refineSpec(") == 1
    assert src.count("void refineSpec(") == 1


def test_poll_spec_job_stops_on_401_and_interrupted(tmp_path):
    if shutil.which("node") is None:
        _missing("node not on PATH")
    esbuild = WEB / "node_modules" / ".bin" / "esbuild"
    if not esbuild.exists():
        _missing("web/node_modules missing; run `npm ci` in web/")

    outfile = tmp_path / "specGen.mjs"
    proc = subprocess.run(
        [str(esbuild), str(WEB / "src" / "specGen.ts"),
         "--bundle", "--format=esm", "--platform=neutral",
         f"--outfile={outfile}"],
        capture_output=True, text=True, timeout=60, check=False,
    )
    assert proc.returncode == 0, f"esbuild specGen.ts failed:\n{proc.stdout}\n{proc.stderr}"

    runner = tmp_path / "run.mjs"
    runner.write_text(
        """
globalThis.window = {
  SITE_CONFIG: { authEnabled: true, supabase: { url: 'http://sb', anon_key: 'a' } },
  location: { href: '/', pathname: '/', search: '', hash: '', origin: 'http://x' },
};
globalThis.localStorage = { getItem() { return null; }, setItem() {}, removeItem() {} };

function jsonResp(status, body) {
  return {
    ok: status >= 200 && status < 300,
    status,
    headers: { get: (n) => n.toLowerCase() === 'content-type' ? 'application/json' : null },
    json: async () => body,
  };
}

const {
  pollSpecJob, shouldOfferRefine, shouldAutoGenerate, shouldAutoFix, specStatusLabel,
  SPEC_AUTH_EXPIRED_MESSAGE, SPEC_INTERRUPTED_MESSAGE, SPEC_POLL_BUDGET_MS,
  SPEC_POLL_INTERVAL_MS, SPEC_POLL_MAX_INTERVAL_MS,
} = await import('./specGen.mjs');

if (shouldOfferRefine({ hf_model_storage_bytes: 10, storage_diff: 2 }) !== true)
  throw new Error('nonzero storage_diff should offer refine');
if (shouldOfferRefine({ hf_model_storage_bytes: 10, storage_diff: 0 }) !== false)
  throw new Error('zero storage_diff should not offer refine');

// A status outside the vocabulary, or none, never reads as `generated`.
for (const [status, label] of [[null, 'unknown'], [undefined, 'unknown'], ['', 'unknown'],
                               ['archived', 'archived'], ['generated', 'generated'],
                               ['needs_repair', 'needs repair'], ['blocked_by_engine', 'engine-blocked']]) {
  if (specStatusLabel(status) !== label) throw new Error(`status ${status}: ${specStatusLabel(status)}`);
}
if (specStatusLabel('contributed', 'https://pr') !== 'PR open') throw new Error('contributed with a PR');
if (specStatusLabel('contributed', null) !== 'no PR') throw new Error('contributed without a PR');

// Only a model with no spec at all is generated by itself; a failure of the
// caller's own spec — an engine gap above all — never starts a paid run.
const graph = { blocks: [1] };
if (shouldAutoGenerate({ success: false, no_spec: true }) !== true)
  throw new Error('no spec at all should generate');
for (const failed of [
  { success: false, served_from: 'user_generation', error_kind: 'blocked_by_engine' },
  { success: false, served_from: 'user_generation', error_kind: 'spec_invalid' },
  { success: false, served_from: 'user_generation' },
  { success: true, served_from: 'user_generation', dashboard: { total_params: 0 }, block_graph: {} },
  { success: false, message: 'No spec matches org/m; run /generate-spec' },
]) {
  if (shouldAutoGenerate(failed) !== false) throw new Error('must not generate: ' + JSON.stringify(failed));
}
if (shouldAutoGenerate({ success: true, dashboard: { total_params: 0 }, block_graph: {} }) !== true)
  throw new Error('a library answer with no graph still offers generation');
if (shouldAutoGenerate({ success: true, dashboard: { total_params: 5 }, block_graph: graph }) !== false)
  throw new Error('a full analysis must not generate');

// A saved spec whose every refusal is a declaration starts Agent Fix;
// an engine gap or a record without an id does not.
if (shouldAutoFix({ success: false, served_from: 'user_generation', fixable: true, record_id: 'rec-1' }) !== true)
  throw new Error('a fixable saved spec should auto-fix');
for (const skipped of [
  { success: false, served_from: 'user_generation', error_kind: 'blocked_by_engine' },
  { success: false, served_from: 'user_generation', error_kind: 'spec_invalid' },
  { success: false, served_from: 'user_generation', fixable: true },
  { success: false, no_spec: true },
  { success: true, served_from: 'user_generation', fixable: true, record_id: 'rec-1' },
]) {
  if (shouldAutoFix(skipped) !== false) throw new Error('must not auto-fix: ' + JSON.stringify(skipped));
}

let fetches = [];
globalThis.fetch = async (url, init) => {
  fetches.push({ url: String(url), auth: init?.headers?.Authorization });
  if (String(url) === '/api/auth/refresh') return jsonResp(200, { ok: true });
  return jsonResp(401, { detail: 'Not authenticated' });
};
const expired = await pollSpecJob('org/m', {
  authed: true,
  sleep: async () => {},
  now: () => 0,
  budgetMs: 60_000,
});
if (expired.success) throw new Error('401 should fail');
if (expired.message !== SPEC_AUTH_EXPIRED_MESSAGE) throw new Error('401 message: ' + expired.message);
if (expired.signInRequired !== true) throw new Error('401 must say a sign-in is required');
if (fetches.length !== 3) throw new Error('expected poll → refresh → retry, got ' + fetches.length);
if (fetches[1].url !== '/api/auth/refresh') throw new Error('second call should refresh the session: ' + fetches[1].url);
if (fetches[0].url !== fetches[2].url) throw new Error('retry should re-poll the same URL');
if (fetches.some((f) => f.auth !== undefined)) throw new Error('cookie auth must not send an Authorization header');

globalThis.fetch = async () => jsonResp(200, { state: 'interrupted', message: SPEC_INTERRUPTED_MESSAGE, events: [] });
const stopped = await pollSpecJob('org/m', {
  authed: true,
  sleep: async () => {},
  now: () => 0,
  budgetMs: 60_000,
});
if (stopped.success) throw new Error('interrupted should fail');
if (stopped.message !== SPEC_INTERRUPTED_MESSAGE) throw new Error('interrupted message: ' + stopped.message);

let n = 0;
const pollAuth = [];
globalThis.fetch = async (url, init) => {
  pollAuth.push(init?.headers?.Authorization);
  n += 1;
  if (n === 1) return jsonResp(200, { state: 'running', events: [{ type: 'log', text: 'hi' }], next_cursor: 1 });
  return jsonResp(200, { state: 'done', success: true, message: 'ok', events: [], next_cursor: 1 });
};
const ok = await pollSpecJob('org/m', {
  authed: true,
  sleep: async () => {},
  now: () => 0,
  budgetMs: 60_000,
});
if (!ok.success || ok.message !== 'ok') throw new Error('done path: ' + JSON.stringify(ok));
if (n < 2) throw new Error('expected repeated polls, got ' + n);
if (pollAuth.some((a) => a !== undefined)) throw new Error('cookie auth must not send an Authorization header');

// A blocked run's machine fields reach the caller: the page picks the
// engine-blocked banner from them, not from the message.
const gaps = [{ capability: 'gather extent', node: 'lm_head', deployments: ['tp8'], stages: ['decode'] }];
globalThis.fetch = async () => jsonResp(200, { state: 'done', success: false, message: 'blocked', next_cursor: 1,
  events: [{ type: 'done', success: false, message: 'blocked', error_kind: 'blocked_by_engine',
             engine_gaps: gaps, record: { outcome: 'recorded', id: 'p1' } }] });
const blocked = await pollSpecJob('org/m', { authed: true, sleep: async () => {}, now: () => 0, budgetMs: 60_000 });
if (blocked.success || blocked.errorKind !== 'blocked_by_engine') throw new Error('blocked: ' + JSON.stringify(blocked));
if (JSON.stringify(blocked.engineGaps) !== JSON.stringify(gaps)) throw new Error('gaps: ' + JSON.stringify(blocked));
if (blocked.record?.outcome !== 'recorded' || blocked.record?.id !== 'p1') throw new Error('record: ' + JSON.stringify(blocked));

// After a restart the job is read back from its log row: the fields ride there.
globalThis.fetch = async () => jsonResp(200, { state: 'done', success: false, message: 'blocked', events: [],
  error_kind: 'blocked_by_engine', engine_gaps: gaps });
const restored = await pollSpecJob('org/m', { authed: true, sleep: async () => {}, now: () => 0, budgetMs: 60_000 });
if (restored.errorKind !== 'blocked_by_engine' || restored.engineGaps?.length !== 1) throw new Error('restored: ' + JSON.stringify(restored));

globalThis.fetch = async () => jsonResp(200, { state: 'mystery' });
const mystery = await pollSpecJob('org/m', {
  authed: true,
  sleep: async () => {},
  now: () => 0,
  budgetMs: 60_000,
});
if (mystery.success) throw new Error('mystery should fail');
if (!String(mystery.message).includes('Unexpected job state')) throw new Error(mystery.message);

if (SPEC_POLL_BUDGET_MS !== (3 * 60 + 10 + 15) * 60 * 1000) throw new Error('budget ' + SPEC_POLL_BUDGET_MS);
let nowCalls = 0;
const timed = await pollSpecJob('org/m', {
  authed: true,
  sleep: async () => { throw new Error('should not sleep past budget'); },
  now: () => { nowCalls += 1; return nowCalls === 1 ? 0 : SPEC_POLL_BUDGET_MS; },
});
if (timed.success) throw new Error('budget should fail');
if (!String(timed.message).includes('Timed out')) throw new Error(timed.message);

// A server whose knobs raise the lock TTL states it; the page polls that long.
let served = 0;
globalThis.fetch = async () => {
  served += 1;
  if (served === 1) return jsonResp(200, { state: 'running', events: [], next_cursor: 0, poll_budget_sec: 2 * SPEC_POLL_BUDGET_MS / 1000 });
  return jsonResp(200, { state: 'done', success: true, message: 'late', events: [], next_cursor: 0 });
};
let clock = 0;
const longer = await pollSpecJob('org/m', {
  authed: true,
  sleep: async () => { clock = SPEC_POLL_BUDGET_MS + 1; },
  now: () => clock,
});
if (!longer.success || longer.message !== 'late') throw new Error('server budget: ' + JSON.stringify(longer));

const sleeps = [];
let fails = 0;
globalThis.fetch = async () => { fails += 1; throw new Error('down'); };
const lost = await pollSpecJob('org/m', {
  authed: true,
  sleep: async (ms) => { sleeps.push(ms); },
  now: () => 0,
  budgetMs: 60_000,
});
if (lost.success) throw new Error('contact loss should fail');
if (!String(lost.message).includes('Lost contact')) throw new Error(lost.message);
if (sleeps[0] !== SPEC_POLL_INTERVAL_MS * 2) throw new Error('first backoff ' + sleeps[0]);
if (Math.max(...sleeps) !== SPEC_POLL_MAX_INTERVAL_MS) throw new Error('backoff cap ' + Math.max(...sleeps));
if (fails < 30) throw new Error('gave up too soon: ' + fails);

console.log('ok');
"""
    )
    run = subprocess.run(
        ["node", str(runner)],
        cwd=tmp_path, capture_output=True, text=True, timeout=30, check=False,
    )
    assert run.returncode == 0, f"pollSpecJob failed:\n{run.stdout}\n{run.stderr}"
