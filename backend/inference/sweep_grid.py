"""Canonical routine shape grid — the single source of truth for the
(context, batch) points every model/op is swept over.

The per-op matrix shapes (GEMM B/s_query/d_reduce/d_out, grouped GEMM
n_tokens/d_reduce/d_out, attention B/s_query/s_kv/n_heads/d_head, …) are *derived*
per model from a fixed grid of deployment points. This module is the one
definition every consumer draws from (the inference Scaling panel, Compare,
the Gallery matrix, and kernel_bench's sweep), so "the routine shapes" means
exactly one thing.

Axes:
  - context (seq)  : ROUTINE_SEQ_LENS — a 9-point log grid, 1K … 1M
  - batch          : ROUTINE_BATCH_GRID — {1, 16, 64, max} per phase, where the
                     "max" sentinel is resolved by the capacity layer (prefill
                     -1 = cap, decode None = KV-bound max_batch)
  - output tokens  : ROUTINE_OUTPUT_TOKENS (decode length held constant)
  - tracks         : ROUTINE_TRACKS / FRONTIER_TRACKS — which (phase, batch
                     keys) a surface asks at each context, as data
                     (`TrackSpec`); a planner is handed one table and
                     branches on no surface name

Consumers:
  - backend.api.routes.gallery         → GALLERY_SEQ_LENS
  - backend.api.gallery_frontier       → FRONTIER_BATCH_GRID / FRONTIER_MAX_GPUS
  - kernel_bench.sweep                 → ROUTINE_TRACKS (Scaling) and
                                          FRONTIER_TRACKS (gallery decode Pareto)
  - web/src/compare.ts (Scaling panel + Compare) → mirrors the seq/batch/output
    grid; there is no runtime config channel, so
    tests/backend/inference/test_sweep_grid.py pins the TS constants to this module.
  - web/src/gallery/axes.json           → parallel presets + weight-dtype options,
    generated by backend.inference.gallery_axes; the same test file pins it.
"""
from __future__ import annotations

from dataclasses import dataclass
from typing import Any, Dict, List, Optional, Tuple

# The one context grid. The routine set every op is measured across; curated
# surfaces name a subset below, never a context outside it.
CONTEXT_GRID: Tuple[int, ...] = (
    1024, 2048, 4096, 8192, 16384, 32768, 131072, 262144, 1048576,
)

# 9-point logarithmic context grid, 1K … 1M. The routine set every op is
# measured across; the Scaling / Compare charts plot exactly these.
ROUTINE_SEQ_LENS: List[int] = list(CONTEXT_GRID)

# Decode length held constant across the context sweep.
ROUTINE_OUTPUT_TOKENS: int = 256

# The Gallery's decode length. Held constant across its sweep — TTFT/TPOT SOL
# is per-step and essentially output-length-invariant; a small value keeps the
# preparation cheap.
GALLERY_OUTPUT_TOKENS: int = 256

# Speculative-decoding presets: K draft tokens per step at acceptance rate α.
# The target verifies K + 1 positions (`phases.Speculation`); K = 0 is plain
# autoregressive decode. The one declaration: the Scaling tracks plan these,
# `/inference/defaults` serves them as `spec_decode_presets`, and
# web/src/compare.ts `SPEC_PRESETS` mirrors them (with the UI labels), pinned
# by tests/backend/inference/test_sweep_grid.py; its `custom` entry is the
# seed of a free-form input, not a preset.
# The acceptance rates are literature estimates, not measurements of any
# particular checkpoint — they shape a first-order decode speedup:
#   mtp    — DeepSeek-V3's native multi-token-prediction head (one MTP
#            layer ⇒ K=1; acceptance ≈ 0.85 per the v3 tech report).
#   medusa — Medusa(-2) heads, K=4; published acceptance ≈ 0.6.
#   eagle  — EAGLE, K=5; published acceptance ≈ 0.7.
SPEC_PRESETS: Dict[str, Dict[str, float]] = {
    "none": {"K": 0, "alpha": 1.0},
    "mtp": {"K": 1, "alpha": 0.85},
    "medusa": {"K": 4, "alpha": 0.6},
    "eagle": {"K": 5, "alpha": 0.7},
}

# Per-phase batch grid. "max" is a sentinel the capacity layer binds: prefill
# -1 → the prefill cap, decode None → the KV-bound max_batch.
ROUTINE_BATCH_GRID: List[Dict[str, Any]] = [
    {"key": "b1",  "prefill_batch_size": 1,  "decode_batch_size": 1},
    {"key": "b16", "prefill_batch_size": 16, "decode_batch_size": 16},
    {"key": "b64", "prefill_batch_size": 64, "decode_batch_size": 64},
    {"key": "max", "prefill_batch_size": -1, "decode_batch_size": None},
]

# The serving page's batch grid: prefill is one interactive request, while
# decode concurrency sweeps. Paired prefill batching remains a measurement
# campaign shape and is outside the serving-law anchor.
SCALING_BATCH_GRID: List[Dict[str, Any]] = [
    {"key": "b1",  "prefill_batch_size": 1, "decode_batch_size": 1},
    {"key": "b16", "prefill_batch_size": 1, "decode_batch_size": 16},
    {"key": "b64", "prefill_batch_size": 1, "decode_batch_size": 64},
    {"key": "max", "prefill_batch_size": 1, "decode_batch_size": None},
]

# The curated context subset: every other decade. The Gallery renders an
# N-model matrix at it, and the Scaling dropdown offers it. 64K is not on the
# measured grid, so no page may offer it until a campaign adds the measurement.
CURATED_CONTEXTS: Tuple[int, ...] = (1024, 4096, 16384, 131072, 1048576)
GALLERY_SEQ_LENS: List[int] = list(CURATED_CONTEXTS)

# The Scaling panel's context dropdown. The panel reads it from
# `/inference/defaults`, and the warm job (backend.api.warm --sweeps) reads it
# here, so a warmed entry lands on the exact key a first visitor's POST
# produces.
SCALING_CONTEXTS: List[int] = list(CURATED_CONTEXTS)

# The largest deployment the parallel sweep enumerates: degrees are powers of
# two up to it. A product bound on what is drawn, not a legality rule — which
# degrees a model admits is the layout's answer (`parallel_sweep.
# legal_parallel_degrees`); a degree past the bound is reported as not
# enumerated, never as refused.
SWEEP_MAX_GPUS: int = 512
GPU_COUNT_GRID: Tuple[int, ...] = tuple(
    1 << shift for shift in range(SWEEP_MAX_GPUS.bit_length())
    if (1 << shift) <= SWEEP_MAX_GPUS
)

# GPU-count ladder the Scaling panel's Context × Batch / KV dropdowns offer,
# shipped the same way (`/inference/defaults`).
SCALING_DEGREES: List[int] = [
    degree for degree in GPU_COUNT_GRID if degree <= 128
]

# The Inference tab's default landing model — the single most common first hit.
# MUST equal web/src/pages/Inference.tsx `DEFAULT_INFER_MODEL`. warm seeds this
# in addition to the featured set so the default page load never computes live.
DEFAULT_INFER_MODEL: str = "deepseek-ai/DeepSeek-V3"

# The Gallery's decode Pareto frontier: every layout up to
# `FRONTIER_MAX_GPUS` (one GPU, then each Scaling-panel mode at 2 … 64 GPUs;
# past a node the collectives cross the inter-node fabric), each at these
# per-GPU decode batches (1, 2, 4, … 1024, then the KV-bound max) at every
# Gallery context. A point is (tokens/s one request sees, tokens/s per GPU);
# the frontier is the points no other point beats on both.
FRONTIER_MAX_GPUS: int = 64
FRONTIER_BATCH_GRID: List[Dict[str, Any]] = [
    *({"key": f"b{1 << i}", "prefill_batch_size": 1, "decode_batch_size": 1 << i}
      for i in range(11)),
    {"key": "max", "prefill_batch_size": 1, "decode_batch_size": None},
]

# The Scaling panel's decode Pareto frontier: a subset of the one batch grid,
# coarser at the low end than the Gallery's (1, then 8 … 1024).
SCALING_DECODE_LADDER: Tuple[int, ...] = tuple(
    int(bp["decode_batch_size"]) for bp in FRONTIER_BATCH_GRID
    if isinstance(bp["decode_batch_size"], int)
    and (bp["decode_batch_size"] == 1 or bp["decode_batch_size"] >= 8)
)

# The frontier's speculative-decoding view, for a model with an MTP draft
# (`speculative_draft.SpeculativeDraft`): the draft lengths K its entry is
# priced at when it is built (each a verify of K + 1 positions plus K
# one-token draft forwards; one sweep of the layout over every K's verify
# width, one walk — every speculative width is the same walk, the width a
# symbol of it — and each K's points read off it by substitution,
# `capacity.CapacitySweepPlan`'s `s_verifies`) — K + 1 a power of two, so
# the verify spans 2, 4, 8, 16 positions — and the acceptance rates
# the page offers — acceptance moves only the tokens a step keeps
# (`phases.Speculation`), so any rate reads the same entry. 0.8 is the
# default: DeepSeek-V3 reports 85–90% for its first MTP token, and later
# draft positions accept less.
FRONTIER_DRAFT_TOKENS: Tuple[int, ...] = (1, 3, 7, 15)
FRONTIER_ACCEPTANCE_RATES: Tuple[float, ...] = (0.6, 0.7, 0.8, 0.9)
FRONTIER_ACCEPTANCE_DEFAULT: float = 0.8


def batch_point(key: str) -> Dict[str, Any]:
    """The grid row for a batch key. Overlapping keys keep the routine row
    (prefill `max` is the cap sentinel); frontier-only rungs (`b2` … `b1024`)
    come from `FRONTIER_BATCH_GRID`."""
    for bp in ROUTINE_BATCH_GRID:
        if bp["key"] == key:
            return bp
    for bp in FRONTIER_BATCH_GRID:
        if bp["key"] == key:
            return bp
    raise ValueError(f"unknown batch key {key!r}")


def requests_needed(key: str, phase: str) -> int:
    """How many concurrent requests must fit for the grid point `key` to
    exist in `phase`: its explicit batch, or one for the `max` sentinel (it
    resolves to however many fit). `capacity.point_served` answers whether
    that many do."""
    bp = batch_point(key)
    batch = bp["prefill_batch_size" if phase == "prefill" else "decode_batch_size"]
    return batch if isinstance(batch, int) and batch > 0 else 1


@dataclass(frozen=True)
class TrackSpec:
    """One kind of question a surface asks at each context: a phase, the
    batch points it reads (keys of `ROUTINE_BATCH_GRID` or
    `FRONTIER_BATCH_GRID`; `max` is the per-GPU capacity ceiling), and
    whether the request reuses a cached prefix.

    `prefix_new_tokens` None is no prefix cache. A number N is "the request
    recomputes its last N tokens": at context L > N the cell runs
    `s_prefix_cached = L − N` (`s_query = N`, `s_kv = L`); at L ≤ N nothing is
    cached, so the track reads the plain cell of its phase.

    `draft_tokens` are the speculative draft lengths K a decode track reads,
    each verified over K + 1 positions in one forward; (0,) is plain
    autoregressive decode, and the only value a prefill track takes (a
    prefill has no draft to verify).

    `geometry` None is the endpoint launch a serving stack asks for;
    `"synthetic_batch"` names a declared kernel-batch point that no scheduler
    issues as one launch. It rides the point's provenance and is never part of
    a key. Chunked prefill is deliberately NOT a geometry string here: its
    scheduler width is a request/deployment/campaign knob, and decomposing an
    endpoint into launch points belongs to the plan-side chunk policy, not to
    this track table."""
    name: str
    phase: str
    batch_keys: Tuple[str, ...]
    prefix_new_tokens: Optional[int] = None
    draft_tokens: Tuple[int, ...] = (0,)
    #: The routing skews ρ a decode/prefill track plans. This is a point
    #: axis, not a deployment field: it changes the busiest routed rank's
    #: geometry.
    ep_load_factors: Tuple[Any, ...] = (1.0,)
    geometry: Optional[str] = None

    def __post_init__(self) -> None:
        if self.phase not in ("prefill", "decode"):
            raise ValueError(f"track {self.name!r}: phase must be prefill or "
                             f"decode, got {self.phase!r}")
        unknown = []
        for k in self.batch_keys:
            try:
                batch_point(k)
            except ValueError:
                unknown.append(k)
        if not self.batch_keys or unknown:
            raise ValueError(f"track {self.name!r}: batch keys must be keys "
                             f"of ROUTINE_BATCH_GRID or FRONTIER_BATCH_GRID, "
                             f"got {list(self.batch_keys)}")
        if self.prefix_new_tokens is not None and not (
                isinstance(self.prefix_new_tokens, int)
                and self.prefix_new_tokens > 0):
            raise ValueError(f"track {self.name!r}: prefix_new_tokens is a "
                             f"positive token count or None, got "
                             f"{self.prefix_new_tokens!r}")
        if (not self.draft_tokens
                or not all(isinstance(k, int) and k >= 0
                           for k in self.draft_tokens)
                or (self.phase == "prefill" and tuple(self.draft_tokens) != (0,))):
            raise ValueError(f"track {self.name!r}: draft_tokens are counts "
                             f"≥ 0, and (0,) on a prefill track; got "
                             f"{self.draft_tokens!r}")
        if self.geometry not in (None, "synthetic_batch"):
            raise ValueError(f"track {self.name!r}: geometry is None or "
                             f"'synthetic_batch', got {self.geometry!r}")
        bad_rho = [rho for rho in self.ep_load_factors
                   if isinstance(rho, bool)
                   or not isinstance(rho, (int, float))
                   or rho < 1]
        if not self.ep_load_factors or bad_rho:
            raise ValueError(f"track {self.name!r}: ep_load_factors are "
                             "numbers ≥ 1, got "
                             f"{list(self.ep_load_factors)!r}")


#: The routine surface (the Scaling panel's Context × Batch, its export,
#: `hbench sweep`): every batch point of both phases, no prefix cache, and
#: decode at every speculative preset the panel offers.
ROUTINE_TRACKS: Tuple[TrackSpec, ...] = (
    TrackSpec("prefill", "prefill", tuple(bp["key"] for bp in ROUTINE_BATCH_GRID)),
    TrackSpec("decode", "decode", tuple(bp["key"] for bp in ROUTINE_BATCH_GRID),
              draft_tokens=tuple(sorted({int(p["K"]) for p in SPEC_PRESETS.values()}))),
)

