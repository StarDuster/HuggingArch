"""Service-only meta endpoint: /site-config.js.

Lives in `backend/service/` rather than `backend/api/routes/meta.py`
because this endpoint exists solely to expose the Supabase URL + anon
key to the frontend; without it the auth/admin pages can't bootstrap.
The OSS core endpoints (/, /health, /dim-glossary, /debug) stay in
backend/api/routes/meta.py.
"""
from __future__ import annotations


from backend import supabase_env

from fastapi.responses import Response

from backend.api._app import app


@app.get("/site-config.js")
def site_config_js():
    """Serve env-injected Supabase config as a JS global.

    web/index.html loads this script, and web/src/auth.ts reads
    `window.SITE_CONFIG.supabase.{url, anon_key}` (fetching the script
    itself when the global is missing).
    The anon key is public-safe (RLS gates per-user access). The
    service-role key never leaves the backend.

    Returns null URL/key when auth isn't configured so the frontend can
    hide login UI gracefully (local-only dev mode).
    """
    url = supabase_env.url() or ""
    anon_key = supabase_env.anon_key() or ""
    auth_on = supabase_env.browser_auth_available()
    payload = (
        "// Auto-generated by /site-config.js — env-driven, do not edit.\n"
        "window.SITE_CONFIG = {\n"
        f"  supabase: {{ url: {url!r}, anon_key: {anon_key!r} }},\n"
        f"  authEnabled: {str(auth_on).lower()},\n"
        "};\n"
    )
    return Response(
        content=payload,
        media_type="application/javascript",
        headers={"Cache-Control": "no-store"},
    )
